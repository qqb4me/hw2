import com.google.gson.Gson;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.ObjectInputStream;
import java.io.ObjectOutputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Random;
import java.util.Scanner;

public class Main {
    static Gson g = new Gson();
    static Scanner sc = new Scanner(System.in);
    static String url = "jdbc:h2:./data/base";
    static String file = "data/last.dat";
    static String txt = "data/last.txt";

    public static void main(String[] args) throws Exception {
        new java.io.File("data").mkdirs();

        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            Statement st = c.createStatement();
            st.execute("create table if not exists posts (id bigint generated by default as identity primary key, " +
                    "pid int, uid int, title varchar(500), body varchar(5000))");
        }

        while (true) {
            System.out.println();
            System.out.println("HTTP - загрузить данные");
            System.out.println("FILE - показать последний файл");
            System.out.println("DB - показать базу");
            System.out.println("EXIT - выход");
            System.out.print("> ");

            String cmd = sc.nextLine().trim().toUpperCase();

            if (cmd.equals("EXIT")) {
                break;
            } else if (cmd.equals("HTTP")) {
                http();
            } else if (cmd.equals("FILE")) {
                file();
            } else if (cmd.equals("DB")) {
                db();
            } else {
                System.out.println("нет такой команды");
            }
        }
    }

    static void http() throws Exception {
        int id = new Random().nextInt(100) + 1;
        HttpClient cl = HttpClient.newHttpClient();
        HttpRequest req = HttpRequest.newBuilder(URI.create("https://jsonplaceholder.typicode.com/posts/" + id))
                .GET().build();
        HttpResponse<String> r = cl.send(req, HttpResponse.BodyHandlers.ofString());

        if (r.statusCode() != 200) {
            System.out.println("ошибка: " + r.statusCode());
            return;
        }

        Post p = g.fromJson(r.body(), Post.class);
        System.out.println(p);

        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            PreparedStatement ps = c.prepareStatement("insert into posts (pid, uid, title, body) values (?, ?, ?, ?)");
            ps.setInt(1, p.id);
            ps.setInt(2, p.userId);
            ps.setString(3, p.title);
            ps.setString(4, p.body);
            ps.executeUpdate();
        }

        try (ObjectOutputStream out = new ObjectOutputStream(new FileOutputStream(file))) {
            out.writeObject(p);
        }

        String s = "id: " + p.id + "\nuser: " + p.userId + "\ntitle: " + p.title + "\nbody: " + p.body;
        try (FileOutputStream out = new FileOutputStream(txt)) {
            out.write(s.getBytes(StandardCharsets.UTF_8));
        }

        String os = System.getProperty("os.name").toLowerCase();
        try {
            if (os.contains("win")) {
                new ProcessBuilder("notepad.exe", txt).start();
            } else if (os.contains("mac")) {
                new ProcessBuilder("open", txt).start();
            } else {
                new ProcessBuilder("xdg-open", txt).start();
            }
        } catch (Exception e) {
            System.out.println("не удалось открыть блокнот");
        }

        System.out.println("сохранено в базу и файл");
    }

    static void file() {
        try (ObjectInputStream in = new ObjectInputStream(new FileInputStream(file))) {
            Post p = (Post) in.readObject();
            System.out.println(p);
        } catch (Exception e) {
            System.out.println("файла пока нет");
        }
    }

    static void db() throws Exception {
        try (Connection c = DriverManager.getConnection(url, "sa", "")) {
            Statement st = c.createStatement();
            ResultSet rs = st.executeQuery("select * from posts order by id");

            while (rs.next()) {
                System.out.println("id: " + rs.getLong("id"));
                System.out.println("post id: " + rs.getInt("pid"));
                System.out.println("user: " + rs.getInt("uid"));
                System.out.println("title: " + rs.getString("title"));
                System.out.println("body: " + rs.getString("body"));
                System.out.println();
            }
        }
    }
}
